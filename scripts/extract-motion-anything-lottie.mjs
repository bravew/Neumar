#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const sourceRoot = path.join(
  repoRoot,
  '_sample/motion-anything/recipes/lottie',
);
const outputFile = path.join(
  repoRoot,
  'packages/video-ir/src/overlay-lottie-assets.generated.ts',
);

const RECIPES = [
  {
    id: 'lottie-favorite',
    assetId: 'motion-anything/lottie-favorite',
    name: 'Lottie Favorite',
    source: 'recipes/lottie/lottie-favorite/animation.json',
  },
  {
    id: 'lottie-fab',
    assetId: 'motion-anything/lottie-fab',
    name: 'Lottie FAB',
    source: 'recipes/lottie/lottie-fab/animation.json',
  },
  {
    id: 'lottie-pagination',
    assetId: 'motion-anything/lottie-pagination',
    name: 'Lottie Pagination',
    source: 'recipes/lottie/lottie-pagination/animation.json',
  },
  {
    id: 'lottie-tab',
    assetId: 'motion-anything/lottie-tab',
    name: 'Lottie Tab',
    source: 'recipes/lottie/lottie-tab/animation.json',
  },
];

function readAnimation(recipe) {
  const file = path.join(sourceRoot, recipe.id, 'animation.json');
  const json = sanitizeLottieJson(JSON.parse(fs.readFileSync(file, 'utf8')));
  const frameRate = Number(json.fr) || 30;
  const inFrame = Number(json.ip) || 0;
  const outFrame = Number(json.op) || inFrame;
  const durationMs = Math.max(
    250,
    Math.round(((outFrame - inFrame) / frameRate) * 1000),
  );
  return {
    ...recipe,
    animationJson: JSON.stringify(json),
    durationMs,
    width: Number(json.w) || 0,
    height: Number(json.h) || 0,
    frameRate,
  };
}

function sanitizeLottieJson(input) {
  const json = JSON.parse(JSON.stringify(input));
  const externalImageAssetIds = new Set();
  if (Array.isArray(json.assets)) {
    for (const asset of json.assets) {
      if (isExternalImageAsset(asset) && typeof asset.id === 'string') {
        externalImageAssetIds.add(asset.id);
      }
    }
    json.assets = json.assets
      .filter((asset) => !isExternalImageAsset(asset))
      .map((asset) => {
        if (Array.isArray(asset.layers)) {
          asset.layers = cleanLayers(asset.layers, externalImageAssetIds);
        }
        return asset;
      });
  }
  if (Array.isArray(json.layers)) {
    json.layers = cleanLayers(json.layers, externalImageAssetIds);
  }
  return json;
}

function isExternalImageAsset(asset) {
  return (
    asset &&
    typeof asset === 'object' &&
    typeof asset.p === 'string' &&
    !asset.p.startsWith('data:')
  );
}

function cleanLayers(layers, externalImageAssetIds) {
  return layers
    .filter((layer) => {
      if (!layer || typeof layer !== 'object') return false;
      if (layer.ty === 2) return false;
      return (
        typeof layer.refId !== 'string' ||
        !externalImageAssetIds.has(layer.refId)
      );
    })
    .map((layer) => {
      if (Array.isArray(layer.layers)) {
        layer.layers = cleanLayers(layer.layers, externalImageAssetIds);
      }
      return layer;
    });
}

function renderTs(assets) {
  const lines = [
    '// Generated by scripts/extract-motion-anything-lottie.mjs.',
    '// Source: _sample/motion-anything/recipes/lottie/*/animation.json.',
    '// Do not edit this file by hand.',
    '',
    'export interface MotionAnythingLottieAssetMeta {',
    '  readonly name: string;',
    '  readonly source: string;',
    '  readonly durationMs: number;',
    '  readonly width: number;',
    '  readonly height: number;',
    '  readonly frameRate: number;',
    '  readonly license: {',
    '    readonly source: string;',
    '    readonly spdx: string;',
    '    readonly attributionRequired: boolean;',
    '  };',
    '}',
    '',
    'export const MOTION_ANYTHING_LOTTIE_ASSETS = {',
  ];

  for (const asset of assets) {
    lines.push(
      `  ${JSON.stringify(asset.assetId)}: ${JSON.stringify(asset.animationJson)},`,
    );
  }

  lines.push(
    '} as const satisfies Record<string, string>;',
    '',
    'export const MOTION_ANYTHING_LOTTIE_ASSET_METADATA = {',
  );

  for (const asset of assets) {
    lines.push(
      `  ${JSON.stringify(asset.assetId)}: {`,
      `    name: ${JSON.stringify(asset.name)},`,
      `    source: ${JSON.stringify(asset.source)},`,
      `    durationMs: ${asset.durationMs},`,
      `    width: ${asset.width},`,
      `    height: ${asset.height},`,
      `    frameRate: ${asset.frameRate},`,
      '    license: {',
      '      source: "motion-anything / spemer/lottie-animations-json",',
      '      spdx: "MIT",',
      '      attributionRequired: true,',
      '    },',
      '  },',
    );
  }

  lines.push(
    '} as const satisfies Record<string, MotionAnythingLottieAssetMeta>;',
    '',
  );

  return `${lines.join('\n')}`;
}

const assets = RECIPES.map(readAnimation);
fs.writeFileSync(outputFile, renderTs(assets), 'utf8');
console.log(
  `Extracted ${assets.length} motion-anything Lottie animation(s) to ${path.relative(
    repoRoot,
    outputFile,
  )}`,
);
