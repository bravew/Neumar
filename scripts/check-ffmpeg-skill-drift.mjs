import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skillRoot = path.join(root, 'skills', 'ffmpeg');
const UNHASHED = new Set(['PROVENANCE.md', 'contract/payload-hashes.txt']);
const HASH_LINE = /^([a-f0-9]{64}) {2}(\S+)$/;
const PUBLIC_TOOL = /^[a-z][a-z0-9]*$/;

const PIN = {
  revision: 'a991599bfe3f072bac3835083f8bbb30efcd9a99',
  packageName: 'ffmpeg-skill',
  version: '2.4.2',
  contractVersion: '1.0',
  toolCount: 42,
  appName: 'ffmpeg',
  modes: ['task', 'design', 'video'],
  server: 'ffmpeg-skill',
  tools: [
    'ffmpeg_skill_catalog',
    'ffmpeg_skill_check',
    'ffmpeg_skill_execute',
  ],
};

const REQUIRED = [
  'LICENSE',
  'PROVENANCE.md',
  'SKILL.md',
  'package.json',
  'contract/contract.json',
  'contract/payload-hashes.txt',
  'docs/contract.md',
  'scripts/_contract.py',
  'scripts/_platforms.py',
  'scripts/_common/__init__.py',
  'scripts/_common/asr.py',
  'scripts/_common/probe.py',
  'scripts/_common/runner.py',
  'references/devices.md',
  'references/gotchas.md',
  'references/scripts.md',
  'templates/reels.json',
  'templates/youtube.json',
];

const GATES = [
  ['raw argv', /\| Raw `argv` \|/],
  ['transcribe', /`transcribe`/],
  ['watch', /\| `batch` `watch` \|/],
  ['saved plan', /\| Saved-plan replay/],
];

function fail(message) {
  throw new Error(message);
}

function read(relativePath) {
  return fs.readFileSync(path.join(skillRoot, relativePath), 'utf8');
}

function listFiles(directory, prefix = '') {
  const found = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === '__pycache__' || entry.name.endsWith('.pyc')) {
      fail(`Payload contains generated bytecode: ${prefix}${entry.name}`);
    }
    const relativePath = prefix + entry.name;
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) found.push(...listFiles(fullPath, `${relativePath}/`));
    else if (entry.isFile()) found.push(relativePath);
    else fail(`Payload contains a non-file entry: ${relativePath}`);
  }
  return found;
}

function sha256(relativePath) {
  return crypto
    .createHash('sha256')
    .update(fs.readFileSync(path.join(skillRoot, relativePath)))
    .digest('hex');
}

function parseHashes(raw) {
  const lines = raw.split('\n');
  if (lines.at(-1) !== '') fail('payload-hashes.txt must end with a newline.');
  const records = new Map();
  for (const line of lines.slice(0, -1)) {
    const match = HASH_LINE.exec(line);
    if (!match) fail(`Malformed payload hash line: ${line}`);
    if (records.has(match[2])) fail(`Duplicate payload hash: ${match[2]}`);
    records.set(match[2], match[1]);
  }
  return records;
}

function assertSorted(values, label) {
  const sorted = [...values].sort();
  if (values.some((value, index) => value !== sorted[index])) {
    fail(`${label} is not sorted.`);
  }
}

function frontmatter(raw) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(raw);
  if (!match) fail('SKILL.md has no frontmatter.');
  const fields = {};
  const lines = match[1].split('\n');
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const field = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
    if (!field) continue;
    if (field[2] === '') {
      const items = [];
      while (lines[index + 1]?.startsWith('  - ')) {
        index += 1;
        items.push(lines[index].slice(4));
      }
      fields[field[1]] = items;
    } else {
      fields[field[1]] = field[2];
    }
  }
  return { fields, body: raw.slice(match[0].length) };
}

function localLinks(markdown) {
  const links = [];
  const pattern = /\[[^\]]*\]\(([^)]+)\)/g;
  for (const match of markdown.matchAll(pattern)) {
    const target = match[1];
    if (/^[a-z]+:/i.test(target)) continue;
    links.push(target.split('#')[0]);
  }
  return links.filter(Boolean);
}

function assertPayload(files, hashes) {
  for (const required of REQUIRED) {
    if (!files.includes(required)) fail(`Missing required payload file: ${required}`);
  }
  const hashed = [...hashes.keys()];
  assertSorted(hashed, 'payload-hashes.txt');
  const expected = files.filter((file) => !UNHASHED.has(file)).sort();
  if (hashed.join('\n') !== expected.join('\n')) {
    const missing = expected.filter((file) => !hashes.has(file));
    const extra = hashed.filter((file) => !expected.includes(file));
    fail(
      `Payload inventory drifted. Missing: ${missing.join(', ') || 'none'}. Extra: ${extra.join(', ') || 'none'}.`,
    );
  }
  for (const [file, expectedHash] of hashes) {
    const actual = sha256(file);
    if (actual !== expectedHash) {
      fail(`Hash drifted for ${file}. Expected ${expectedHash}, got ${actual}.`);
    }
  }
}

function publicScripts(files) {
  return files
    .filter((file) => /^scripts\/[a-z0-9_]+\.py$/.test(file))
    .map((file) => path.basename(file, '.py'))
    .filter((name) => PUBLIC_TOOL.test(name) && !name.startsWith('_'))
    .sort();
}

function assertContract(files) {
  const contract = JSON.parse(read('contract/contract.json'));
  if (contract.contract_version !== PIN.contractVersion) {
    fail(`Contract version is ${contract.contract_version}, pin is ${PIN.contractVersion}.`);
  }
  if (contract.skill?.id !== PIN.packageName || contract.skill?.version !== PIN.version) {
    fail('Contract skill id or version does not match the pin.');
  }
  if (!Array.isArray(contract.tools) || contract.tools.length !== PIN.toolCount) {
    fail(`Contract has ${contract.tools?.length ?? 0} tools; pin requires ${PIN.toolCount}.`);
  }
  const names = contract.tools.map((tool) => tool?.name);
  if (names.some((name) => typeof name !== 'string' || !PUBLIC_TOOL.test(name))) {
    fail('Contract contains a tool without a public script name.');
  }
  const sorted = [...names].sort();
  if (new Set(sorted).size !== sorted.length) fail('Contract tool names are not unique.');
  const scripts = publicScripts(files);
  if (sorted.join('\n') !== scripts.join('\n')) {
    fail('Contract tool names do not match scripts/*.py public tools.');
  }
  for (const tool of contract.tools) {
    if (tool.id !== `${PIN.packageName}/${tool.name}`) {
      fail(`Tool ${tool.name} has upstream id ${tool.id}.`);
    }
    if (tool.executable !== `scripts/${tool.name}.py`) {
      fail(`Tool ${tool.name} points at ${tool.executable}.`);
    }
    if (!files.includes(tool.executable)) fail(`Missing executable ${tool.executable}.`);
    const schema = tool.input_schema;
    if (schema?.type !== 'object' || schema.additionalProperties !== false) {
      fail(`Tool ${tool.name} has no closed object input schema.`);
    }
    if (!schema.properties || typeof schema.properties !== 'object') {
      fail(`Tool ${tool.name} has no input properties.`);
    }
    for (const [key, property] of Object.entries(schema.properties)) {
      const cli = property?.cli;
      const positional = cli === 'positional';
      const flags = Array.isArray(cli) && cli.every((flag) => typeof flag === 'string');
      if (!positional && !flags) fail(`Tool ${tool.name} argument ${key} has no CLI spelling.`);
    }
    if (!Array.isArray(tool.mcp?.positional)) {
      fail(`Tool ${tool.name} has no MCP positional map.`);
    }
  }
}

function assertSkill() {
  const skill = frontmatter(read('SKILL.md'));
  if (skill.fields.name !== PIN.appName) {
    fail(`SKILL.md name is ${skill.fields.name}; app name must stay ${PIN.appName}.`);
  }
  const description = skill.fields.description;
  if (typeof description !== 'string' || description.length < 1 || description.length > 1024) {
    fail('SKILL.md description is missing or longer than 1024 characters.');
  }
  if (JSON.stringify(skill.fields.modes) !== JSON.stringify(PIN.modes)) {
    fail(`SKILL.md modes must be ${PIN.modes.join(', ')}.`);
  }
  if (!skill.body.includes(`MCP server name: \`${PIN.server}\``)) {
    fail(`SKILL.md does not name the ${PIN.server} MCP server.`);
  }
  for (const tool of PIN.tools) {
    if (!skill.body.includes(tool)) fail(`SKILL.md does not name ${tool}.`);
  }
  for (const [label, pattern] of GATES) {
    if (!pattern.test(skill.body)) fail(`SKILL.md does not gate ${label}.`);
  }
  for (const link of localLinks(skill.body)) {
    if (!fs.existsSync(path.join(skillRoot, link))) {
      fail(`SKILL.md links to missing payload path ${link}.`);
    }
  }
}

function assertPackage() {
  const manifest = JSON.parse(read('package.json'));
  if (manifest.name !== PIN.packageName || manifest.version !== PIN.version) {
    fail('package.json upstream name or version changed.');
  }
  if (manifest.license !== 'MIT') fail('package.json license is not MIT.');
}

function assertProvenance() {
  const provenance = read('PROVENANCE.md');
  for (const value of [PIN.revision, PIN.version, PIN.contractVersion, 'MIT']) {
    if (!provenance.includes(value)) fail(`PROVENANCE.md is missing ${value}.`);
  }
  if (!/^## Local patch inventory/m.test(provenance)) {
    fail('PROVENANCE.md has no local patch inventory.');
  }
}

function assertNoSampleDependency(files) {
  const sampleRoot = path.join(root, '_sample');
  const script = fs.readFileSync(fileURLToPath(import.meta.url), 'utf8');
  if (script.includes(sampleRoot)) {
    fail('Drift check must not read the sample checkout.');
  }
  for (const file of files) {
    if (file.split('/').includes('_sample')) {
      fail(`Payload path enters the sample checkout: ${file}`);
    }
  }
}

export function checkFfmpegSkillDrift() {
  const files = listFiles(skillRoot).sort();
  assertSorted(files, 'payload walk');
  assertPayload(files, parseHashes(read('contract/payload-hashes.txt')));
  assertContract(files);
  assertSkill();
  assertPackage();
  assertProvenance();
  assertNoSampleDependency(files);
  return PIN;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--self-test')) {
    const original = fs.readFileSync;
    fs.readFileSync = (file, encoding) => {
      const text = original.call(fs, file, encoding);
      if (typeof text !== 'string') return text;
      return typeof file === 'string' && file.endsWith(`${path.sep}SKILL.md`)
        ? text.replace('name: ffmpeg', 'name: ffmpeg-skill')
        : text;
    };
    try {
      checkFfmpegSkillDrift();
    } catch (error) {
      fs.readFileSync = original;
      if (error instanceof Error && error.message.includes('app name')) {
        console.log('FFmpeg drift guard mismatch self-test passed.');
        process.exit(0);
      }
      throw error;
    }
    fs.readFileSync = original;
    fail('FFmpeg drift guard accepted a renamed skill.');
  }

  const pin = checkFfmpegSkillDrift();
  console.log(
    `FFmpeg skill matches ${pin.packageName} ${pin.version} (${pin.revision.slice(0, 12)}, ${pin.toolCount} tools).`,
  );
}
