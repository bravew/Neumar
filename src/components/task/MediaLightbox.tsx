// ── Inline chat document chip (markdown, code, text, json, csv, …) ─────────

/** 5 MB cap — keeps a rogue big log from freezing the webview on decode. */
const INLINE_DOC_MAX_BYTES = 5 * 1024 * 1024;

/**
 * Clickable chip for any text-previewable file (markdown / code / txt / json /
 * csv / yaml / …). Click lazy-loads the content via `POST /files/read` and
 * opens the shared lightbox in text mode.
 */
export function InlineChatDocument({
  path,
  name,
  provenance,
}: {
  path: string;
  name?: string;
  provenance?: MediaProvenanceInfo;
}) {
  const { t } = useLanguage();
  const [open, setOpen] = useState(false);
  const [content, setContent] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const loadingRef = useRef(false);
  const displayName = name ?? path.split('/').pop()?.split('?')[0] ?? 'file';
  const ext = extOf(displayName);
  const language: 'markdown' | 'code' | 'html' =
    ext === 'html' || ext === 'htm'
      ? 'html'
      : MARKDOWN_EXTS.has(ext)
        ? 'markdown'
        : 'code';

  const handleOpen = async () => {
    setOpen(true);
    if (content !== null || error !== null) return;
    if (loadingRef.current) return;
    loadingRef.current = true;
    try {
      const res = await fetch(`${API_BASE_URL}/files/read`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ path }),
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const body = (await res.json()) as { content?: string; error?: string };
      if (body.error) throw new Error(body.error);
      const raw = body.content ?? '';
      if (raw.length > INLINE_DOC_MAX_BYTES) {
        setError(
          `File too large to preview (${Math.round(raw.length / 1024 / 1024)} MB). Open it externally instead.`,
        );
      } else {
        setContent(raw);
      }
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to load preview');
    } finally {
      loadingRef.current = false;
    }
  };

  if (!path) return null;
  return (
    <>
      <div className="my-3 inline-flex max-w-full items-center">
        <button
          type="button"
          onClick={handleOpen}
          className="border-border/60 bg-muted/40 hover:bg-muted/70 flex items-center gap-2 rounded-lg border px-3 py-2 text-sm transition-colors"
          title={t.task.lightboxViewFull}
          aria-label={`${t.task.lightboxViewFull} — ${displayName}`}
        >
          <FileText className="text-muted-foreground size-4 shrink-0" />
          <span className="max-w-[260px] truncate">{displayName}</span>
          <MediaProvenanceBadge provenance={provenance} variant="inline" />
        </button>
      </div>
      {open && (content !== null || error !== null) && (
        <MediaLightbox
          src=""
          alt={displayName}
          type="text"
          textContent={error ?? content ?? ''}
          textLanguage={language}
          provenance={provenance}
          onClose={() => setOpen(false)}
        />
      )}
    </>
  );
}

// ── Helpers ──────────────────────────────────────────────────────────────────

/** Extract local file path from a /files/stream?path=... URL. */
function extractLocalPath(url: string): string | null {
  try {
    if (url.includes('/files/stream?path=')) {
      const u = new URL(url, 'http://localhost');
      return u.searchParams.get('path');
    }
  } catch {
    /* not a valid URL */
  }
  return null;
}
